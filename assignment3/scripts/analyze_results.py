def tick_label(p: int) -> str:
    """Hide the 20 and 24 labels, which overlap on the log2 axis."""
    return "" if p in (20, 24) else str(p)


def mark_topology(ax) -> None:
    """Vertical guides: 8 P-cores, 16 P-core threads, 28 logical processors."""
    for x, label in ((8, "8 P-cores"), (16, "16 P-threads"), (28, "28 logical")):
        ax.axvline(x, color="grey", ls=":", lw=1)
        ax.text(x, ax.get_ylim()[1], label, rotation=90, va="top", ha="right",
                fontsize=7, color="grey")


def fig_time(summary: pd.DataFrame) -> None:
    th = summary[summary["experiment"] == "threads"]
    fig, ax = plt.subplots(figsize=(7, 4.3))
    for i, n in enumerate(sorted(th["n"].unique())):
        c = SIZE_COLORS[i % len(SIZE_COLORS)]
        d = th[(th["method"] == PAR) & (th["n"] == n)].sort_values("threads_or_workers")
        ax.plot(d["threads_or_workers"], d["median_ms"], "o-", color=c, label=f"$n={n}$")
        ax.fill_between(d["threads_or_workers"], d["q1_ms"], d["q3_ms"], color=c, alpha=0.2)
        t_seq = th[(th["method"] == SEQ) & (th["n"] == n)]["median_ms"].iloc[0]
        ax.axhline(t_seq, color=c, ls="--", lw=0.9)
    ax.set_xscale("log", base=2)
    ax.set_yscale("log")
    pvals = sorted(th[th["method"] == PAR]["threads_or_workers"].unique())
    ax.set_xticks(pvals)
    ax.set_xticklabels([tick_label(p) for p in pvals])
    ax.set_xlabel("Number of threads $p$")
    ax.set_ylabel("Kernel execution time [ms]")
    ax.set_title("Parallel tiled kernel: time vs threads\n"
                 "(median, shaded IQR; dashed = sequential baseline median)")
    mark_topology(ax)
    ax.legend(fontsize=8, ncol=2)
    fig.tight_layout()
    save(fig, "fig_time_vs_threads.png")


def fig_speedup_efficiency(scal: pd.DataFrame) -> None:
    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(10, 4.2))
    pvals = sorted(scal["threads_or_workers"].unique())
    for i, n in enumerate(sorted(scal["n"].unique())):
        c = SIZE_COLORS[i % len(SIZE_COLORS)]
        d = scal[scal["n"] == n]
        yerr = np.vstack([d["speedup"] - d["speedup_lo"], d["speedup_hi"] - d["speedup"]])
        ax1.errorbar(d["threads_or_workers"], d["speedup"], yerr=yerr, fmt="o-",
                     color=c, capsize=2, ms=4, label=f"$n={n}$")
        ax2.plot(d["threads_or_workers"], d["efficiency"], "o-", color=c, ms=4,
                 label=f"$n={n}$")
    ax1.plot(pvals, pvals, "k--", lw=1, label="Ideal $S(p)=p$")
    ax1.set_ylim(0, max(30, scal["speedup_hi"].max() * 1.1))
    ax1.set_xlabel("Number of threads $p$")
    ax1.set_ylabel("Speedup $S(p)$ (from medians)")
    ax1.set_title("Speedup (error bars: IQR of $T_p$)")
    ax2.axhline(1.0, color="k", ls="--", lw=1)
    ax2.set_ylim(0, 1.15)
    ax2.set_xlabel("Number of threads $p$")
    ax2.set_ylabel("Efficiency $E(p)=S(p)/p$")
    ax2.set_title("Parallel efficiency")
    for ax in (ax1, ax2):
        ax.set_xscale("log", base=2)
        ax.set_xticks(pvals)
        ax.set_xticklabels([tick_label(p) for p in pvals])
        mark_topology(ax)
    ax1.legend(fontsize=8)
    fig.tight_layout()
    save(fig, "fig_speedup_efficiency.png")


def fig_simd(summary: pd.DataFrame) -> None:
    sm = summary[summary["experiment"] == "simd"]
    if sm.empty:
        return
    p_par = int(sm[sm["method"] == "tiled_par_vec"]["threads_or_workers"].max())
    labels = {"tiled_seq_novec": "Sequential, novec", "tiled_seq_vec": "Sequential, vec",
              "tiled_par_novec": f"Parallel p={p_par}, novec",
              "tiled_par_vec": f"Parallel p={p_par}, vec"}
    colors = {"tiled_seq_novec": "#aec7e8", "tiled_seq_vec": "#1f77b4",
              "tiled_par_novec": "#ffbb78", "tiled_par_vec": "#ff7f0e"}
    sizes = sorted(sm["n"].unique())
    x = np.arange(len(sizes))
    w = 0.2
    fig, ax = plt.subplots(figsize=(7, 4.2))
    for j, m in enumerate(SIMD_ORDER):
        d = sm[sm["method"] == m].set_index("n").reindex(sizes)
        err = np.vstack([d["median_ms"] - d["q1_ms"], d["q3_ms"] - d["median_ms"]])
        ax.bar(x + (j - 1.5) * w, d["median_ms"], w, yerr=err, capsize=2,
               color=colors[m], label=labels[m])
    ax.set_xticks(x)
    ax.set_xticklabels([f"$n={n}$" for n in sizes])
    ax.set_yscale("log")
    ax.set_xlabel("Matrix dimension $n$")
    ax.set_ylabel("Kernel execution time [ms]")
    ax.set_title("SIMD extension: vectorised vs non-vectorised builds\n"
                 "(median, error bars = IQR)")
    ax.legend(fontsize=8)
    fig.tight_layout()
    save(fig, "fig_simd.png")


def save(fig, name: str) -> None:
    FIG_DIR.mkdir(parents=True, exist_ok=True)
    path = FIG_DIR / name
    fig.savefig(path)
    plt.close(fig)
    print(f"wrote {path}")


# ---------------------------------------------------------------------------

def main() -> None:
    raw = load_raw()
    summary = summarize(raw)
    REPORT_DIR.mkdir(parents=True, exist_ok=True)
    summary.to_csv(REPORT_DIR / "summary_statistics.csv", index=False, float_format="%.6f")
    print(f"wrote {REPORT_DIR / 'summary_statistics.csv'}")

    failed = raw[raw["status"] != "OK"]
    if not failed.empty:
        print("Non-OK rows (reported, not timed):")
        print(failed[["experiment", "method", "n", "threads_or_workers",
                      "repetition_id", "status"]].to_string(index=False))

    table_tune(summary, 2000, "table_tune.tex", "tab:tune", "Row-tile tuning")
    table_tune(summary, 4000, "table_probe.tex", "tab:probe",
               "Row-tile probe of the large-$n$ slowdown")
    table_placement()
    if (summary["experiment"] == "threads").any():
        scal = scaling_table(summary)
        scal.to_csv(REPORT_DIR / "scaling_statistics.csv", index=False, float_format="%.6f")
        table_time(summary)
        table_speedup(scal)
        table_memory(summary)
        fig_time(summary)
        fig_speedup_efficiency(scal)
    table_simd(summary)
    fig_simd(summary)


if __name__ == "__main__":
    main()
