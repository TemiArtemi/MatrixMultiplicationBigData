#!/usr/bin/env python3
"""
Analysis pipeline for Assignment 3.

Reads the raw measurement CSVs produced by the C harness
(assignment3/data/results/results_a3_*.csv), computes the protocol
statistics (median and interquartile range of the measured repetitions,
warm-ups excluded), derives speedup S(p) = T_seq / T_p and efficiency
E(p) = S(p) / p from MEDIAN times, and regenerates every table and figure
used in the report:

  report/summary_statistics.csv   - full statistics table (machine readable)
  report/tables/*.tex             - booktabs tables included by the report
  report/figures/*.png            - all report figures

Run from anywhere:  python assignment3/scripts/analyze_results.py
"""

import glob
import sys
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

BASE = Path(__file__).resolve().parent.parent
RESULTS_DIR = BASE / "data" / "results"
REPORT_DIR = BASE / "report"
FIG_DIR = REPORT_DIR / "figures"
TAB_DIR = REPORT_DIR / "tables"

plt.rcParams.update({
    "figure.dpi": 130,
    "savefig.dpi": 160,
    "font.size": 10,
    "axes.grid": True,
    "grid.alpha": 0.3,
    "legend.loc": "best",
})

SEQ = "tiled_seq_vec"
PAR = "tiled_par_vec"
SIMD_ORDER = ["tiled_seq_novec", "tiled_seq_vec", "tiled_par_novec", "tiled_par_vec"]
SIZE_COLORS = ["#1f77b4", "#ff7f0e", "#2ca02c", "#d62728", "#9467bd", "#8c564b"]


# ---------------------------------------------------------------------------
# Loading and statistics
# ---------------------------------------------------------------------------

def load_raw() -> pd.DataFrame:
    files = sorted(glob.glob(str(RESULTS_DIR / "results_a3_*.csv")))
    if not files:
        sys.exit(f"No results_a3_*.csv found in {RESULTS_DIR}")
    frames = []
    for f in files:
        df = pd.read_csv(f)
        df["source_file"] = Path(f).name
        frames.append(df)
        print(f"loaded {Path(f).name}: {len(df)} rows")
    return pd.concat(frames, ignore_index=True)


def summarize(raw: pd.DataFrame) -> pd.DataFrame:
    """Median / IQR per configuration; TIMEOUT rows are counted, not timed."""
    keys = ["experiment", "method", "n", "threads_or_workers", "row_tile",
            "block_size"]
    rows = []
    for k, g in raw[raw["repetition_id"] >= 1].groupby(keys):
        ok = g[g["status"] == "OK"]
        t = ok["execution_time_ms"]
        rows.append({
            **dict(zip(keys, k)),
            "reps_ok": len(ok),
            "reps_failed": int((g["status"] != "OK").sum()),
            "median_ms": t.median() if len(ok) else np.nan,
            "q1_ms": t.quantile(0.25) if len(ok) else np.nan,
            "q3_ms": t.quantile(0.75) if len(ok) else np.nan,
            "iqr_ms": (t.quantile(0.75) - t.quantile(0.25)) if len(ok) else np.nan,
            "mean_ms": t.mean() if len(ok) else np.nan,
            "std_ms": t.std() if len(ok) > 1 else np.nan,
            "median_peak_mb": ok["memory_value_mb"].median() if len(ok) else np.nan,
            "theoretical_storage_mb": g["theoretical_storage_mb"].iloc[0],
        })
    s = pd.DataFrame(rows)
    s["n"] = s["n"].astype(int)
    s["threads_or_workers"] = s["threads_or_workers"].astype(int)
    return s.sort_values(keys).reset_index(drop=True)


def scaling_table(summary: pd.DataFrame) -> pd.DataFrame:
    """Speedup and efficiency from medians for the threads experiment."""
    th = summary[summary["experiment"] == "threads"]
    seq = th[th["method"] == SEQ].set_index("n")["median_ms"]
    par = th[th["method"] == PAR].copy()
    par["t_seq_ms"] = par["n"].map(seq)
    par["speedup"] = par["t_seq_ms"] / par["median_ms"]
    par["efficiency"] = par["speedup"] / par["threads_or_workers"]
    # Speedup range induced by the IQR of T_p (T_seq median held fixed).
    par["speedup_lo"] = par["t_seq_ms"] / par["q3_ms"]
    par["speedup_hi"] = par["t_seq_ms"] / par["q1_ms"]
    return par.sort_values(["n", "threads_or_workers"]).reset_index(drop=True)


# ---------------------------------------------------------------------------
# Tables
# ---------------------------------------------------------------------------

def fmt_ms(median: float, iqr: float) -> str:
    if np.isnan(median):
        return "--"
    if median >= 1000:
        return f"{median:,.0f} [{iqr:,.0f}]".replace(",", "{,}")
    return f"{median:.1f} [{iqr:.1f}]"


def write_tex(name: str, lines: list[str]) -> None:
    TAB_DIR.mkdir(parents=True, exist_ok=True)
    path = TAB_DIR / name
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {path}")


def table_time(summary: pd.DataFrame) -> None:
    th = summary[summary["experiment"] == "threads"]
    sizes = sorted(th["n"].unique())
    reps = int(th["reps_ok"].max())
    lines = [
        r"% Auto-generated by scripts/analyze_results.py -- do not edit.",
        r"\begin{table}[H]",
        r"\centering",
        r"\small",
        r"\caption{Kernel execution time in ms, median [IQR] of $N=%d$ measured "
        r"repetitions (1 warm-up excluded). Sequential baseline and parallel "
        r"implementation with $p$ threads.}" % reps,
        r"\label{tab:time}",
        r"\begin{tabular}{l" + "r" * len(sizes) + "}",
        r"\toprule",
        "Configuration & " + " & ".join(f"$n={n}$" for n in sizes) + r" \\",
        r"\midrule",
    ]
    seq = th[th["method"] == SEQ].set_index("n")
    lines.append("Sequential & " + " & ".join(
        fmt_ms(seq.loc[n, "median_ms"], seq.loc[n, "iqr_ms"]) for n in sizes) + r" \\")
    lines.append(r"\midrule")
    par = th[th["method"] == PAR]
    for p in sorted(par["threads_or_workers"].unique()):
        d = par[par["threads_or_workers"] == p].set_index("n")
        lines.append(f"Parallel $p={p}$ & " + " & ".join(
            fmt_ms(d.loc[n, "median_ms"], d.loc[n, "iqr_ms"]) if n in d.index else "--"
            for n in sizes) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table}"]
    write_tex("table_time.tex", lines)


def table_speedup(scal: pd.DataFrame) -> None:
    sizes = sorted(scal["n"].unique())
    lines = [
        r"% Auto-generated by scripts/analyze_results.py -- do not edit.",
        r"\begin{table}[H]",
        r"\centering",
        r"\small",
        r"\caption{Speedup $S(p)=T_{\mathrm{seq}}(n)/T_p(n)$ and, in parentheses, "
        r"efficiency $E(p)=S(p)/p$, both computed from median times.}",
        r"\label{tab:speedup}",
        r"\begin{tabular}{l" + "c" * len(sizes) + "}",
        r"\toprule",
        "$p$ & " + " & ".join(f"$n={n}$" for n in sizes) + r" \\",
        r"\midrule",
    ]
    for p in sorted(scal["threads_or_workers"].unique()):
        d = scal[scal["threads_or_workers"] == p].set_index("n")
        cells = []
        for n in sizes:
            if n in d.index and not np.isnan(d.loc[n, "speedup"]):
                cells.append(f"{d.loc[n, 'speedup']:.2f} ({d.loc[n, 'efficiency']:.2f})")
            else:
                cells.append("--")
        lines.append(f"{p} & " + " & ".join(cells) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table}"]
    write_tex("table_speedup.tex", lines)


def table_memory(summary: pd.DataFrame) -> None:
    th = summary[summary["experiment"] == "threads"]
    sizes = sorted(th["n"].unique())
    pmax = int(th[th["method"] == PAR]["threads_or_workers"].max())
    p_logical = 28 if 28 in th["threads_or_workers"].values else pmax
    configs = [("Sequential", SEQ, 1), ("Parallel $p=1$", PAR, 1),
               (f"Parallel $p={p_logical}$", PAR, p_logical)]
    if pmax != p_logical:
        configs.append((f"Parallel $p={pmax}$", PAR, pmax))
    lines = [
        r"% Auto-generated by scripts/analyze_results.py -- do not edit.",
        r"\begin{table}[H]",
        r"\centering",
        r"\small",
        r"\caption{Peak process working set (RSS) in MB, median of the measured "
        r"repetitions, versus the theoretical storage of $A$, $B$ and $C$ "
        r"($3\cdot 8n^2$ bytes).}",
        r"\label{tab:memory}",
        r"\begin{tabular}{l" + "r" * len(sizes) + "}",
        r"\toprule",
        "Configuration & " + " & ".join(f"$n={n}$" for n in sizes) + r" \\",
        r"\midrule",
    ]
    storage = th.groupby("n")["theoretical_storage_mb"].first()
    lines.append("Theoretical $A,B,C$ & " + " & ".join(
        f"{storage[n]:.1f}" for n in sizes) + r" \\")
    lines.append(r"\midrule")
    for label, method, p in configs:
        d = th[(th["method"] == method) & (th["threads_or_workers"] == p)].set_index("n")
        lines.append(label + " & " + " & ".join(
            f"{d.loc[n, 'median_peak_mb']:.1f}" if n in d.index else "--"
            for n in sizes) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table}"]
    write_tex("table_memory.tex", lines)


def table_simd(summary: pd.DataFrame) -> None:
    sm = summary[summary["experiment"] == "simd"]
    if sm.empty:
        print("no SIMD results; skipping table_simd.tex")
        return
    p_par = int(sm[sm["method"] == "tiled_par_vec"]["threads_or_workers"].max())
    lines = [
        r"% Auto-generated by scripts/analyze_results.py -- do not edit.",
        r"\begin{table}[H]",
        r"\centering",
        r"\small",
        r"\caption{SIMD extension: kernel time in ms, median [IQR] ($N=%d$), of "
        r"the non-vectorised (\texttt{-fno-tree-vectorize}) and vectorised "
        r"builds of the same source, at $p=1$ (sequential) and $p=%d$. "
        r"Gain $=T_{\mathrm{novec}}/T_{\mathrm{vec}}$ (medians).}"
        % (int(sm["reps_ok"].max()), p_par),
        r"\label{tab:simd}",
        r"\begin{tabular}{rrrcrrc}",
        r"\toprule",
        r" & \multicolumn{3}{c}{Sequential ($p=1$)} & "
        r"\multicolumn{3}{c}{Parallel ($p=%d$)} \\" % p_par,
        r"\cmidrule(lr){2-4}\cmidrule(lr){5-7}",
        r"$n$ & novec & vec & gain & novec & vec & gain \\",
        r"\midrule",
    ]
    for n in sorted(sm["n"].unique()):
        d = sm[sm["n"] == n].set_index("method")
        cells = [str(n)]
        for nv, v in (("tiled_seq_novec", "tiled_seq_vec"),
                      ("tiled_par_novec", "tiled_par_vec")):
            if nv in d.index and v in d.index:
                cells += [fmt_ms(d.loc[nv, "median_ms"], d.loc[nv, "iqr_ms"]),
                          fmt_ms(d.loc[v, "median_ms"], d.loc[v, "iqr_ms"]),
                          f"{d.loc[nv, 'median_ms'] / d.loc[v, 'median_ms']:.2f}"]
            else:
                cells += ["--", "--", "--"]
        lines.append(" & ".join(cells) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table}"]
    write_tex("table_simd.tex", lines)


def table_placement() -> None:
    """Placement diagnostic: 1-thread runs under three Windows policies."""
    policies = [
        ("placement_diag_A_default.csv", "Windows default (EcoQoS on, any core)"),
        ("placement_diag_B_ecoqos_off.csv", "EcoQoS opt-out, any core"),
        ("placement_diag_C_ecoqos_off_pcores.csv", "EcoQoS opt-out, P-cores only"),
    ]
    diag_dir = RESULTS_DIR / "placement_diagnostic"
    frames = {}
    for fname, label in policies:
        path = diag_dir / fname
        if path.exists():
            d = pd.read_csv(path)
            frames[label] = d[(d["repetition_id"] >= 1) & (d["status"] == "OK")]
    if not frames:
        return
    any_df = next(iter(frames.values()))
    sizes = sorted(any_df["n"].unique())
    reps = int(any_df.groupby(["method", "n"]).size().max())
    row_tile = int(any_df["row_tile"].iloc[0])
    lines = [
        r"% Auto-generated by scripts/analyze_results.py -- do not edit.",
        r"\begin{table}[H]",
        r"\centering",
        r"\small",
        r"\caption{Placement diagnostic: 1-thread kernel time in ms, median "
        r"[IQR] of $N=%d$ repetitions (row tile %d), for the sequential "
        r"baseline and the parallel build with $p=1$, under three Windows "
        r"placement policies. Both columns execute identical work.}"
        % (reps, row_tile),
        r"\label{tab:placement}",
        r"\begin{tabular}{l" + "rr" * len(sizes) + "}",
        r"\toprule",
        " & " + " & ".join(r"\multicolumn{2}{c}{$n=%d$}" % n for n in sizes) + r" \\",
        "".join(r"\cmidrule(lr){%d-%d}" % (2 + 2 * i, 3 + 2 * i) for i in range(len(sizes))),
        "Policy & " + " & ".join(["Seq.", "Par. $p=1$"] * len(sizes)) + r" \\",
        r"\midrule",
    ]
    for label, d in frames.items():
        cells = []
        for n in sizes:
            for m in (SEQ, PAR):
                t = d[(d["n"] == n) & (d["method"] == m)]["execution_time_ms"]
                cells.append(fmt_ms(t.median(), t.quantile(0.75) - t.quantile(0.25)))
        lines.append(label + " & " + " & ".join(cells) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table}"]
    write_tex("table_placement.tex", lines)


def table_tune(summary: pd.DataFrame, n: int, fname: str, label: str,
               title: str) -> None:
    """Row-tile sweep at one size: sequential and every parallel p tested."""
    tu = summary[(summary["experiment"] == "tune") & (summary["n"] == n)]
    if tu.empty:
        return
    pvals = sorted(tu[tu["method"] == PAR]["threads_or_workers"].unique())
    lines = [
        r"% Auto-generated by scripts/analyze_results.py -- do not edit.",
        r"\begin{table}[H]",
        r"\centering",
        r"\small",
        r"\caption{%s at $n=%d$: kernel time in ms, "
        r"median [IQR] of $N=%d$ repetitions.}" % (title, n, int(tu["reps_ok"].max())),
        r"\label{%s}" % label,
        r"\begin{tabular}{rrr" + "r" * (1 + len(pvals)) + "}",
        r"\toprule",
        r"Row tile & k/j tile & Row tiles & Sequential & "
        + " & ".join(f"Parallel $p={int(p)}$" for p in pvals) + r" \\",
        r"\midrule",
    ]
    combos = tu[["row_tile", "block_size"]].drop_duplicates()
    combos = combos.sort_values(["block_size", "row_tile"], ascending=[False, True])
    for bi, bs in combos.itertuples(index=False):
        d = tu[(tu["row_tile"] == bi) & (tu["block_size"] == bs)]
        seq = d[d["method"] == SEQ].iloc[0]
        cells = [str(int(bi)), str(int(bs)), str(-(-n // int(bi))),
                 fmt_ms(seq["median_ms"], seq["iqr_ms"])]
        for p in pvals:
            r = d[(d["method"] == PAR) & (d["threads_or_workers"] == p)].iloc[0]
            cells.append(fmt_ms(r["median_ms"], r["iqr_ms"]))
        lines.append(" & ".join(cells) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table}"]
    write_tex(fname, lines)


