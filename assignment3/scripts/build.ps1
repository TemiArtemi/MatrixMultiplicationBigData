# build.ps1 - Build the Assignment 3 harness (run from the repository root).
#
# The tiled kernel (a3_kernels.c) is compiled four times from the SAME source:
#   seq/par   : without / with -fopenmp (sequential baseline vs parallel)
#   vec/novec : with / without the GCC tree vectoriser (SIMD extension)
# Every kernel object also writes a GCC vectorisation report, and the packed
# AVX2 FMA instructions of each object are counted with objdump as evidence
# of (absence of) vectorisation. Evidence files go to assignment3/data/results.

$ErrorActionPreference = "Stop"

$src = "assignment3\src\c"
$build = "assignment3\build"
$results = "assignment3\data\results"
New-Item -ItemType Directory -Force $build | Out-Null
New-Item -ItemType Directory -Force $results | Out-Null

$common = @("-march=native", "-Wall", "-Wextra")
$kernelBase = @("-O3") + $common
$variants = @(
    @{ suffix = "_seq_vec";   flags = @("-Wno-unknown-pragmas") },
    @{ suffix = "_par_vec";   flags = @("-fopenmp") },
    @{ suffix = "_seq_novec"; flags = @("-fno-tree-vectorize", "-Wno-unknown-pragmas") },
    @{ suffix = "_par_novec"; flags = @("-fopenmp", "-fno-tree-vectorize") }
)

$objects = @()
foreach ($v in $variants) {
    $obj = "$build\k$($v.suffix).o"
    $report = "$results\vec_report$($v.suffix).txt"
    $args = $kernelBase + $v.flags + @(
        "-DA3_KERNEL_SUFFIX=$($v.suffix)",
        "-fopt-info-vec-optimized=$report",
        "-c", "$src\a3_kernels.c", "-o", $obj
    )
    Write-Host "gcc $($args -join ' ')"
    & gcc @args
    if ($LASTEXITCODE -ne 0) { throw "kernel build failed ($($v.suffix))" }
    $objects += $obj
}

# Support modules: not performance critical, compiled as in Assignment 2.
$support = @("a3_timer", "a3_matrix", "a3_registry", "a3_validate", "a3_affinity",
             "a3_sysinfo", "a3_bench")
foreach ($m in $support) {
    $obj = "$build\$m.o"
    $args = @("-O2") + $common + @("-fopenmp", "-c", "$src\$m.c", "-o", $obj)
    & gcc @args
    if ($LASTEXITCODE -ne 0) { throw "build failed ($m)" }
    $objects += $obj
}

$exe = "$src\a3_bench.exe"
& gcc -fopenmp -o $exe @objects -lpsapi
if ($LASTEXITCODE -ne 0) { throw "link failed" }
Write-Host "Built $exe"

# SIMD evidence: count packed (ymm) and scalar double FMA instructions.
$evidence = @("# Generated by scripts/build.ps1 -- objdump instruction counts per kernel object",
              "object,packed_ymm_fma_pd,scalar_fma_sd,vectorised_loops_reported")
foreach ($v in $variants) {
    $obj = "$build\k$($v.suffix).o"
    $asm = & objdump -d --no-show-raw-insn $obj
    $packed = ($asm | Select-String -Pattern "vfmadd\w*pd\s.*%ymm").Count
    $scalar = ($asm | Select-String -Pattern "vfmadd\w*sd\s").Count
    $loops = (Get-Content "$results\vec_report$($v.suffix).txt" |
              Select-String -Pattern "loop vectorized").Count
    $evidence += "k$($v.suffix).o,$packed,$scalar,$loops"
}
$evidence | Set-Content -Encoding utf8 "$results\simd_evidence.csv"
$evidence | ForEach-Object { Write-Host $_ }

# Excerpt of the innermost loop of the vectorised parallel kernel.
& objdump -d --no-show-raw-insn "$build\k_par_vec.o" |
    Select-String -Pattern "vfmadd\w*pd" -Context 3, 3 |
    Select-Object -First 3 |
    Out-String |
    Set-Content -Encoding utf8 "$results\objdump_excerpt_par_vec.txt"
